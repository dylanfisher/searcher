/// A rectangle in layout coordinates, where y grows downward. Foundation alone doesn't give
/// `CGRect` its members, and Browser stays free of CoreGraphics, so Interface converts at the
/// boundary.
public struct Rect: Equatable, Sendable {
    public var x: Double
    public var y: Double
    public var width: Double
    public var height: Double

    public init(x: Double, y: Double, width: Double, height: Double) {
        self.x = x
        self.y = y
        self.width = width
        self.height = height
    }

    public var minX: Double { x }
    public var minY: Double { y }
    public var maxX: Double { x + width }
    public var maxY: Double { y + height }
}
